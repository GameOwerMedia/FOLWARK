import { build } from 'esbuild';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.join(root,'portable');
await mkdir(out,{recursive:true});
const result=await build({absWorkingDir:root,entryPoints:['src/main.ts'],bundle:true,format:'iife',minify:true,write:false,outdir:out,loader:{'.woff2':'dataurl','.woff':'dataurl'},target:'es2022',legalComments:'eof'});
const js=result.outputFiles.find(f=>f.path.endsWith('.js')).text;
const css=result.outputFiles.find(f=>f.path.endsWith('.css')).text;
const files=(await readdir(path.join(root,'public/assets'))).filter(name=>name.endsWith('.png')).map(name=>name.slice(0,-4));
const assets={};
for(const name of files)assets[name]='data:image/png;base64,'+(await readFile(path.join(root,'public/assets',name+'.png'))).toString('base64');
const html='<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>FOLWARK | Survival and power</title><link rel="icon" href="data:,"><style>'+css+'</style></head><body><div id="loading"><strong>FOLWARK</strong><div class="loader-line"></div><span>Otwieramy bramy folwarku...</span></div><div id="shell"></div><script>window.FOLWARK_ASSETS='+JSON.stringify(assets)+';<\/script><script>'+js.replace(/<\/script/gi,'<\\/script')+'<\/script></body></html>';
const target=path.join(out,'GRAJ-FOLWARK.html');
let licenseText='';
for(const name of await readdir(path.join(root,'public/licenses')))licenseText+='\n'+name+'\n'+await readFile(path.join(root,'public/licenses',name),'utf8');
await writeFile(target,html+'\n<!-- Third-party and source licenses\n'+licenseText.replaceAll('--',' - ')+'\n-->');
console.log('Portable game:',target,'('+Math.round(Buffer.byteLength(html)/1024/1024)+' MB)');
